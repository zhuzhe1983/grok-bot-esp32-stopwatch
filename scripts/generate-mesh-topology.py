#!/usr/bin/env python3
"""Closed, outward-wound topology for the existing 64 x 9 body surfaces."""
from pathlib import Path

vertices=[(0,0,1),(0,0,-1)]
ids={}
for side in (1,-1):
    for ring in range(1,8):
        for angle in range(64):
            ids[side,ring,angle]=len(vertices)
            vertices.append((ring,angle,side))
for angle in range(64):
    ids[0,8,angle]=len(vertices)
    vertices.append((8,angle,0))
def vertex(side,ring,angle):
    if not ring:return 0 if side==1 else 1
    return ids[0 if ring==8 else side,ring,angle%64]
faces=[]
for side in (1,-1):
    for ring in range(1,9):
        for i in range(64):
            p,c,n,q=(vertex(side,ring-1,i),vertex(side,ring,i),vertex(side,ring,i+1),vertex(side,ring-1,i+1))
            for face in [(p,c,n)]+([(p,n,q)] if ring>1 else []):
                faces.append(face if side==1 else (face[0],face[2],face[1]))
edges={}
for index,face in enumerate(faces):
    for a,b in zip(face,face[1:]+face[:1]):
        key=tuple(sorted((a,b)))
        if key in edges:
            e=edges[key]
            assert e[:2]==[b,a] and len(e)==3
            e.append(index)
        else:edges[key]=[a,b,index]
assert all(len(e)==4 for e in edges.values())
assert len(vertices)-len(edges)+len(faces)==2
output=['/* Generated by scripts/generate-mesh-topology.py; existing geometry unchanged. */',
        '#pragma once','#include <stdint.h>',
        f'enum {{ MESH_VERTICES={len(vertices)},MESH_FACES={len(faces)},MESH_EDGES={len(edges)} }};',
        'static const struct {uint8_t ring,angle;int8_t side;} mesh_vertices[MESH_VERTICES]={']
output.extend('    {'+','.join(map(str,v))+'},' for v in vertices)
output.append('};\nstatic const uint16_t mesh_faces[MESH_FACES][3]={')
output.extend('    {'+','.join(map(str,v))+'},' for v in faces)
output.append('};\nstatic const uint16_t mesh_edges[MESH_EDGES][4]={')
output.extend('    {'+','.join(map(str,v))+'},' for v in edges.values())
output.append('};\n')
root=Path(__file__).resolve().parents[1]
(root/'components/agent_interaction/interaction_mesh_topology.h').write_text('\n'.join(output))
print(f'{len(vertices)} vertices; {len(faces)} faces; {len(edges)} manifold edges')
